let str=" shailendra singh ";

// concat
let cc=str.concat(31)
console.log(cc)

// indexOf()
let ind=str.indexOf("a")
console.log(ind)

// lastindexOf()
let lastind=str.lastIndexOf("a")
console.log(lastind)

// startsWith
let st=str.startsWith("s")
console.log(st)

// endsWith
let en=str.endsWith("singh")
console.log(en)

//search
let src=str.search("singh")
console.log(src)

// repeat()
let rp=str.repeat(3)
console.log(rp)

// toUpperCase()
let up=str.toUpperCase()
console.log(up)

// toLowerCase()
let lo=str.toLowerCase()
console.log(lo)

//split string into array
let sp=str.split(' ')
console.log(sp)

//slice()
let sl=str.slice(0,4)
console.log(sl)

// substring()
let ss=str.substring(0,4)
console.log(ss)

// trim()
let tr=str.trim()
console.log(tr)

// includes()
let inc = str.includes("singh")
console.log(inc)

// replace()
let rep=str.replace('singh','yadav')
console.log(rep)

// charAt()
let ch=str.charAt(10)
console.log(ch)

// charcodeAt()
let cca=str.charCodeAt(0)
console.log(cca)